const enErrors: Record<string, string> = {
  EMPTY_TRANSCRIPT: "Enter a meeting transcript",
  TRANSCRIPT_TOO_SHORT: "The transcript is too short to analyze",
  TRANSCRIPT_TOO_LONG: "Keep the transcript under 50,000 characters",
  INVALID_REQUEST: "Check the meeting requirements and transcript, then try again.",
  MISSING_API_KEY: "AI analysis is temporarily unavailable",
  TIMEOUT: "AI analysis is temporarily unavailable",
  PROVIDER_ERROR: "AI analysis is temporarily unavailable",
  INVALID_OUTPUT: "AI analysis is temporarily unavailable",
  STALE_ANALYSIS: "The meeting changed during analysis. Analyze the current version again.",
};
export function translate(
  locale: Locale,
  key: string,
  params: Record<string, string | number> = {},
): string {
  let result = locale === "zh" ? (zh[key] ?? key) : (enErrors[key] ?? key);
  for (const [name, value] of Object.entries(params))
    result = result.replaceAll(`{${name}}`, String(value));
  return result;
}

// Translate only proven built-in role labels; the participant's name remains untouched.
export function requirementLabel(
  locale: Locale,
  r: { label: string; kind: string; builtinKey?: string },
) {
  if (r.builtinKey !== r.label) return r.label;
  if (r.kind === "speaker")
    return r.label.replace(
      /（(Product|Engineering|Sales|Customer|Other)）$/,
      (_, role: string) => `（${translate(locale, role)}）`,
    );
  return translate(locale, r.label);
}
